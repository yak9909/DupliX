# Builds src/gpu/fast_raster.cu into PTX and embeds it as a byte array in src/gpu/fast_raster_ptx.h (generated,
# not in git). Called by tools/build.ps1 inside the VS developer shell (nvcc needs cl.exe to preprocess).
# The CUDA 12.2 toolkit and compute_52 keep the PTX loadable by older drivers too; the driver compiles it for the
# GPU at load time, so users need only the NVIDIA driver.
$ErrorActionPreference = "Stop"
$root = Resolve-Path (Join-Path $PSScriptRoot "..")
$cu = Join-Path $root "src\gpu\fast_raster.cu"
$hdr = Join-Path $root "src\gpu\fast_raster_ptx.h"
$nvcc = "C:\Program Files\NVIDIA GPU Computing Toolkit\CUDA\v12.2\bin\nvcc.exe"
if ((Test-Path $hdr) -and (Get-Item $hdr).LastWriteTime -gt (Get-Item $cu).LastWriteTime -and
    (Get-Item $hdr).LastWriteTime -gt (Get-Item $PSCommandPath).LastWriteTime) { return }
$ptx = Join-Path $root "build\obj\fast_raster.ptx"
New-Item -ItemType Directory -Force (Split-Path $ptx) | Out-Null
# The VS 2022 STL refuses CUDA < 12.4 (STL1002); the kernel uses no STL, so the check is switched off.
& $nvcc -ptx -arch=compute_52 -O3 -allow-unsupported-compiler -D_ALLOW_COMPILER_AND_STL_VERSION_MISMATCH -o $ptx $cu
if ($LASTEXITCODE -ne 0) { throw "nvcc failed ($LASTEXITCODE)" }
$bytes = [IO.File]::ReadAllBytes($ptx)
$sb = [Text.StringBuilder]::new()
[void]$sb.AppendLine("// Generated by tools/build_ptx.ps1 from src/gpu/fast_raster.cu. Do not edit.")
[void]$sb.AppendLine("#pragma once")
[void]$sb.Append("static const unsigned char kFastRasterPtx[] = {")
for ($i = 0; $i -lt $bytes.Length; $i++) {
    if ($i % 24 -eq 0) { [void]$sb.Append("`n    ") }
    [void]$sb.Append($bytes[$i]).Append(",")
}
[void]$sb.AppendLine("`n    0};")
[IO.File]::WriteAllText($hdr, $sb.ToString())
Write-Host "PTX: $($bytes.Length) bytes -> $hdr"
