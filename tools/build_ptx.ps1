# Builds the CUDA kernels into PTX and embeds each as a byte array in a generated header (not in git):
#   src/gpu/fast_raster.cu -> src/gpu/fast_raster_ptx.h (kFastRasterPtx)
#   src/gpu/ae_span.cu     -> src/gpu/ae_span_ptx.h     (kAeSpanPtx; --fmad=false: AE's exact arithmetic)
# Called by tools/build.ps1 inside the VS developer shell (nvcc needs cl.exe to preprocess).
# The CUDA 12.2 toolkit and compute_52 keep the PTX loadable by older drivers too; the driver compiles it for the
# GPU at load time, so users need only the NVIDIA driver.
$ErrorActionPreference = "Stop"
$root = Resolve-Path (Join-Path $PSScriptRoot "..")
$nvcc = "C:\Program Files\NVIDIA GPU Computing Toolkit\CUDA\v12.2\bin\nvcc.exe"
$kernels = @(
    @{ Cu = "src\gpu\fast_raster.cu"; Hdr = "src\gpu\fast_raster_ptx.h"; Var = "kFastRasterPtx"; Flags = @(); Deps = @() },
    @{ Cu = "src\gpu\ae_span.cu"; Hdr = "src\gpu\ae_span_ptx.h"; Var = "kAeSpanPtx"; Flags = @("--fmad=false");
       Deps = @("src\core\ae_span_impl.h") }
)
foreach ($k in $kernels) {
    $cu = Join-Path $root $k.Cu
    $hdr = Join-Path $root $k.Hdr
    $inputs = @($cu, $PSCommandPath) + @($k.Deps | ForEach-Object { Join-Path $root $_ })
    $fresh = Test-Path $hdr
    if ($fresh) {
        $t = (Get-Item $hdr).LastWriteTime
        foreach ($i in $inputs) { if ((Get-Item $i).LastWriteTime -gt $t) { $fresh = $false } }
    }
    if ($fresh) { continue }
    $ptx = Join-Path $root ("build\obj\" + [IO.Path]::GetFileNameWithoutExtension($cu) + ".ptx")
    New-Item -ItemType Directory -Force (Split-Path $ptx) | Out-Null
    # The VS 2022 STL refuses CUDA < 12.4 (STL1002); the kernels use no STL, so the check is switched off.
    & $nvcc -ptx -arch=compute_52 -O3 -allow-unsupported-compiler -D_ALLOW_COMPILER_AND_STL_VERSION_MISMATCH @($k.Flags) -o $ptx $cu
    if ($LASTEXITCODE -ne 0) { throw "nvcc failed ($LASTEXITCODE) for $($k.Cu)" }
    $bytes = [IO.File]::ReadAllBytes($ptx)
    $sb = [Text.StringBuilder]::new()
    [void]$sb.AppendLine("// Generated by tools/build_ptx.ps1 from $($k.Cu -replace '\\', '/'). Do not edit.")
    [void]$sb.AppendLine("#pragma once")
    [void]$sb.Append("static const unsigned char $($k.Var)[] = {")
    for ($i = 0; $i -lt $bytes.Length; $i++) {
        if ($i % 24 -eq 0) { [void]$sb.Append("`n    ") }
        [void]$sb.Append($bytes[$i]).Append(",")
    }
    [void]$sb.AppendLine("`n    0};")
    [IO.File]::WriteAllText($hdr, $sb.ToString())
    Write-Host "PTX: $($bytes.Length) bytes -> $hdr"
}
